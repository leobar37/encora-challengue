import alias from "@rollup/plugin-alias";
import { nodeResolve } from "@rollup/plugin-node-resolve";
import replace from "@rollup/plugin-replace";
import commonjs from "@rollup/plugin-commonjs";
import { resolve } from "node:path/posix";
import json from "@rollup/plugin-json";
import type { Plugin, RollupOptions } from "rollup";
import esbuild from "rollup-plugin-esbuild";

export type Options = {
  dir: string;
};

export const getConfig = async (options: Options): Promise<RollupOptions> => {
  const { dir } = options;
  const cwd = process.cwd();
  const pkg = await import(resolve(cwd, "package.json"));

  const isCli = !!pkg?.bin;

  const plugins: Plugin[] = [
    nodeResolve({
      extensions: [".js", ".jsx", ".ts", ".tsx"],
      preferBuiltins: true,
    }),
    commonjs({
      ignore: ["readable-stream", "glob"],
    }),
    json(),
    alias({}),
    esbuild({
      sourceMap: !isCli,
      tsconfig: resolve(dir, "tsconfig.json"),
    }),
    replace({
      preventAssignment: true,
    }),
    // preserveDirectives(),
  ];

  // Why?
  const deps = [
    ...Object.keys(pkg.dependencies || {}),
    ...Object.keys(pkg.peerDependencies || {}),
  ];

  const external = deps.length ? new RegExp(`^(${deps.join("|")})`) : undefined;

  const outputs: RollupOptions["output"] = [
    {
      format: "es",
      exports: "named",
      entryFileNames: "[name].js",
      dir: "dist/esm",
      preserveModules: false,
      banner: "// This file is generated by rollup-plugin-esbuild",
    },
    {
      format: "cjs",
      exports: "named",
      entryFileNames: "[name].cjs",
      preserveModules: false,
      dir: "dist/cjs",
      banner: "// This file is generated by rollup-plugin-esbuild",
    },
  ];

  return {
    input: ["./src/index.ts"],
    output: outputs,
    external,
    plugins,
  };
};
